/**
 * What the model is told, generated from the gate's own constants.
 *
 * Every list here is derived rather than hand-written. A prompt that advertises
 * a library the allowlist refuses, or omits one it permits, costs a paid
 * request to discover — the codegen canary lost three generations to exactly
 * this class of drift between what was asked for and what was accepted.
 *
 * The prompt describes a contract and a set of capabilities. It does not
 * describe a product, a page, a set of sections or a layout, because the entire
 * point of replacing the page schema was to stop doing that. What to build is
 * the brief's business; how to structure it is the model's.
 */

import { ALLOWED_EXTENSIONS, ALLOWED_PATH_ROOTS, APP_BUDGETS, APP_SCHEMA_VERSION, RESERVED_PATHS } from "./contract";
import { PATCH_SCHEMA_VERSION } from "./edit";
import {
  MARKER_PREFIX, PATCH_CLOSE, PATCH_OPEN, PROJECT_CLOSE, PROJECT_OPEN,
  encodeFramedFiles, fileClose, fileOpen,
} from "./framing";
import { describeRuntime, RUNTIME_TEMPLATES, type RuntimeTemplateId } from "./runtime";

export function appSystemPrompt(template: RuntimeTemplateId = "react-spa"): string {
  const scaffold = RUNTIME_TEMPLATES[template];
  return `You write complete React applications. Return one framed document and nothing else — no prose, no markdown fence around the whole response.

FORMAT
A small JSON header, then every file as raw text between markers. File
contents are NOT JSON strings: do not escape quotes, newlines, backslashes or
anything else inside them. Write the file exactly as it should appear on disk.

${PROJECT_OPEN}
{
  "schemaVersion": "${APP_SCHEMA_VERSION}",
  "metadata": { "name": string, "description": string, "locale": string },
  "runtime": { "template": "${template}", "dependencies": string[] },
  "routes": [{ "path": "/", "module": "${scaffold.root}", "title": string }],
  "manifest": ["${scaffold.root}", "src/styles.css"]
}
${PROJECT_CLOSE}
${fileOpen(scaffold.root)}
import "./styles.css";

export default function App() {
  return <div className="p-6">It can contain "quotes", \`backticks\`, \\ and 日本語.</div>;
}
${fileClose(scaffold.root)}
${fileOpen("src/styles.css")}
.example { color: #111; }
${fileClose("src/styles.css")}

RULES FOR THE FRAME
- Every marker sits alone on its own line, exactly as written above.
- Every file in "manifest" gets exactly one block, and every block's path is
  in "manifest". No extras, no omissions, no duplicates.
- The closing marker repeats the same path as the opening one.
- File contents may never contain the text "${MARKER_PREFIX}".
- Only the header is JSON. Escaping anything inside a file block is a bug.

WHAT YOU OWN
The component tree, the file structure, the state, the interactions, the
layout, the typography and the colour system. Build the application the brief
describes. There is no page template and no section vocabulary to fill in —
two different briefs should produce two applications with nothing structural
in common.

Build a real application, not a description of one. If the brief implies
filtering, filtering must work. If it implies a form, the form must validate
and respond. Client-side state, derived values, conditional rendering, modals,
tabs, keyboard handling — all of it is available and all of it is expected.

FILES
- ${scaffold.root} must exist and default-export the root component.
- ${scaffold.entry} is written by Ventrio. Do not supply it.
- Paths start with ${ALLOWED_PATH_ROOTS.join(" or ")} and end with ${ALLOWED_EXTENSIONS.join(", ")}.
- Any structure you like inside those roots. Nested component folders are
  encouraged; one enormous file is not.
- These are generated by Ventrio and will be refused: ${RESERVED_PATHS.join(", ")}.
- Import a stylesheet the normal way (\`import "./styles.css"\`).

LIBRARIES — these and only these
${describeRuntime()}
Declare in \`runtime.dependencies\` exactly what you import. You cannot install
anything: there is no package manager, no CDN and no network.

THE ENVIRONMENT IS SEALED
The app runs in a sandboxed frame with no network and no storage. These are
not discouraged, they are unavailable, and using even one of them fails the
build outright — the project is refused, not degraded:
fetch, XMLHttpRequest, WebSocket, EventSource, sendBeacon, localStorage,
sessionStorage, indexedDB, document.cookie, eval, new Function, import.meta,
window.parent / top / opener, service workers, require().

That includes a "persistence" or "storage" helper module. A generated project
was refused for one src/utils/storage.ts wrapping localStorage; everything
else about it was fine. There is no persistence layer to write.

Hold everything in React state — useState, useReducer, context. Seed it from
a source file you import. State resets when the preview reloads, and that is
the expected behaviour, not a bug to work around.

WHAT TO BUILD, AND WHEN
Build what was asked for. If the brief describes an application, build the
working application. If it asks for a landing page or a marketing page, build
that page. If it is ambiguous but describes something people use, build the
application.

Never substitute a marketing page, a waitlist, a signup mock or an
explanation of what the product could become for the functionality that was
requested. A page describing the tool is not the tool.

FORMS
Every form validates before it submits. Required fields are enforced, invalid
values are refused with a message next to the field that caused it, and a
successful submission visibly confirms itself — the new item appears, or the
form reports what it did. A form that accepts an empty submit silently is a
defect, and a generated app shipped with exactly that.

BUDGETS
Up to ${APP_BUDGETS.maxFiles} files, ${Math.round(APP_BUDGETS.maxFileBytes / 1000)} kB per file,
${Math.round(APP_BUDGETS.maxTotalSourceBytes / 1000)} kB total, ${APP_BUDGETS.maxRoutes} routes.

IMAGERY
There is no image host. An external URL — Unsplash, a CDN, anything starting
http — is refused by the gate and blocked by the sandbox, and a generation
shipped nine broken avatars that way.

Compose without photography. Initials in a shaped container, an inline SVG you
write yourself, a gradient or duotone field, a bold type treatment, a CSS
pattern: all of these are available and none of them can break. If the layout
seems to want a picture, give that space something that is actually there —
never an empty box, a grey placeholder, or a column reserved for an image that
will not load.

TYPOGRAPHY — 12px MINIMUM, ENFORCED
Never write a font size below 12px for text a person reads. Not labels, not
chips, not captions, not metadata, not table cells, not badges, not footnotes.
The build is refused if the compiled CSS contains a smaller size.

These exact utilities are the ones that keep getting written, and every one of
them is refused:

  FORBIDDEN — refused by the build
    text-[10px]  text-[11px]  text-[9px]
    text-[0.625rem]  text-[0.6875rem]
    any arbitrary font size computing below 12px, in px, rem or em

  ALLOWED — use these instead
    text-xs        12px — the smallest permitted, for genuinely minor text
    text-[12px]    12px — the same thing spelled out; the floor, not below it
    text-[0.75rem] 12px — also fine
    text-sm        14px — labels, captions, supporting copy
    text-base      16px — body copy and controls

Body copy and controls read best at 14–16px. Small is not the same as refined.

Before you finish, read back every font-size utility and every font-size
declaration you have authored, in every file, and confirm each one that applies
to readable text is 12px or larger. This is the single most common reason a
project is refused.

This constrains text only. Arbitrary values for spacing, borders, radii, icon
dimensions, line heights, tracking and non-text CSS are unaffected — a 10px gap
or a 1px rule is fine.

ART DIRECTION
Choose the palette, type and surface treatment from the product and the brief.
A tool for accountants and a site for a record label should not look related.

Do not reach for the default: violet-to-indigo gradients on the logo tile and
the primary button are what every generated app looks like, and a reviewer
called exactly that out as template-like. Pick a colour because the product
means something by it, then use it consistently — one accent, earned surfaces,
and contrast that comes from hierarchy rather than from saturation.

QUALITY
- Mobile first. Nothing may overflow horizontally at 390px. Compose the small
  screen deliberately; a compressed desktop layout reads as one.
- Type at a readable measure. A body column narrower than about 40 characters
  is a bug, not a style.
- Every control does something. A button wired to nothing is worse than absent.
- One structural idea carried consistently beats five decorations.
- Real states: empty, selected, invalid, submitted. A control that does
  nothing is worse than a control that is absent.
- Label controls, and keep keyboard users in mind — a modal needs a way out.`;
}

export function appUserPrompt(brief: string): string {
  return `${brief}\n\nReturn the framed document now.`;
}

/**
 * What the model is shown of the project it is being asked to repair.
 *
 * A patch is a diff against a base, and the request that carries it is a fresh
 * single-turn call: the model has no memory of what it returned a minute ago.
 * Asking for a patch without stating the base is asking it to edit a file it
 * cannot see, so the context is a required argument rather than an optional
 * one — the type is the check.
 */
export interface AppRepairContext {
  /** Every path in the project, so a patch never re-invents a file that exists. */
  manifest: string[];
  /** Complete current contents of the files the patch is expected to touch. */
  files: Record<string, string>;
  /** True when `files` is a subset — the prompt then says so explicitly. */
  partial: boolean;
}

/**
 * The repair prompt.
 *
 * It carries the exact diagnostics and asks for a patch rather than a rewrite.
 * A repair that returns a whole new project throws away everything that was
 * already right, and the failure list is usually three lines long.
 *
 * When only some files are shown, the prompt says so in as many words. A model
 * shown four of eleven files and not told the rest exist rewrites them from
 * memory, and a patch that "restores" nine files it never saw is exactly the
 * whole-project regeneration this path exists to avoid.
 */
/**
 * What a repair must not break while fixing what it was asked to fix.
 *
 * THE DEFECT THIS ADDRESSES. A production repair was sent to correct a single
 * framing error and returned a project carrying eight new font sizes below the
 * 12px floor, across five components. The repair fixed its named problem and
 * failed the gate on a rule it had introduced violations of — so the run cost
 * two provider requests and produced nothing.
 *
 * A repair is answering a refusal, and every rule that applied to the original
 * project still applies to the repaired one. The validator runs again afterwards
 * regardless and remains the authority; this is here so the model knows that
 * before it writes, rather than discovering it in a diagnostic it never sees.
 */
const REPAIR_CONSTRAINTS = `EVERY ORIGINAL RULE STILL APPLIES
Fixing the problems listed above does not suspend anything else. The repaired
project is validated again in full, and a repair that fixes its named failure
while introducing a different one is refused exactly like the first attempt.

In particular, do not introduce text below the 12px minimum. Never write
text-[10px], text-[11px], text-[0.625rem], text-[0.6875rem], or any arbitrary
font size computing below 12px, in px, rem or em. Use text-xs (12px) as the
smallest readable size, text-sm (14px) for labels and captions, text-base (16px)
for body. This applies to every file you touch, including ones you are only
editing for an unrelated reason. Non-text values — spacing, borders, radii, icon
sizes — are unaffected.

Before returning, re-read the font sizes in every file you are sending back and
confirm each one that applies to readable text is 12px or larger.`;

export function appRepairPrompt(diagnostics: string[], context: AppRepairContext): string {
  // Shown in the same frame the answer must use, so the format is demonstrated
  // rather than only described.
  const shown = encodeFramedFiles(context.files);

  return `The project you returned was refused. Fix exactly these problems and change nothing else.

${diagnostics.map((line) => `- ${line}`).join("\n")}

THE PROJECT AS IT STANDS
${context.manifest.map((path) => `- ${path}`).join("\n")}
${context.partial
    ? "\nOnly the files below are reproduced. Every other file above is unchanged\nand will be kept — do not rewrite one from memory.\n"
    : ""}
${shown}

Return a patch, not a whole project, in the same framed format:

${PATCH_OPEN}
{
  "schemaVersion": "${PATCH_SCHEMA_VERSION}",
  "summary": "<one line>",
  "write": ["<path you are changing>"],
  "remove": ["<path to delete>"]
}
${PATCH_CLOSE}
${fileOpen("<path you are changing>")}
<the complete new contents of that file, raw and unescaped>
${fileClose("<path you are changing>")}

"write" lists the paths whose blocks follow; every listed path needs a block
and every block needs to be listed. Include the complete contents of each file
you change. Files you do not mention are kept as they are. File contents are
never JSON strings and may never contain "${MARKER_PREFIX}".

The environment has not changed: no localStorage, sessionStorage, indexedDB,
cookies, service workers, fetch or eval. Hold state in React. Do not fix a
problem by replacing working functionality with a simpler page.

${REPAIR_CONSTRAINTS}`;
}

/**
 * The other repair: start again, with the failures attached.
 *
 * Used when there is no base to patch — the response was not JSON, or it was
 * refused by validation, and in neither case does a project exist that
 * `applyPatch` could be applied to. The brief is restated because this is a
 * fresh single-turn request and the model has not seen it since.
 *
 * The refused project is not echoed back. It can be 300 kB, the failure list
 * already says what was wrong with it, and returning a refused document invites
 * a patch around the rule rather than compliance with it.
 */
export function appRewritePrompt(brief: string, diagnostics: string[]): string {
  return `${brief}

YOUR PREVIOUS PROJECT WAS REFUSED. Fix every point below and return the whole
project again in the framed format: the JSON header between ${PROJECT_OPEN}
and ${PROJECT_CLOSE}, then one raw block per file. File contents are not JSON
strings — do not escape anything inside them.

${diagnostics.slice(0, 25).map((line) => `- ${line}`).join("\n")}

Build the same product the brief asked for. Fixing a refusal by shipping less
than was requested — a marketing page instead of the application, a form
without validation — is not a fix.

${REPAIR_CONSTRAINTS}`;
}
